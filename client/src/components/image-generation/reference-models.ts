/**
 * SM-26: генерация по образцу (референс).
 *
 * Референс принимает только модель `fal-ai/nano-banana-pro/edit` — у остальных
 * такого входа нет, это ограничение самих моделей, а не наше решение. Здесь
 * единственный источник правды: какая это модель, как она называется
 * по-человечески, сколько образцов можно приложить и что уходит в тело запроса.
 */

/** Идентификатор модели, которая умеет генерировать по образцу. */
export const REFERENCE_MODEL_ID = 'fal-ai/nano-banana-pro/edit';

/**
 * Человеческое название. В списке моделей раньше стояло `NanoBanana Pro/Edit` —
 * это читается как код, и человек не догадывался, что за ним прячется
 * «сгенерируй похожее на мою картинку». Название должно называть возможность.
 */
export const REFERENCE_MODEL_LABEL = 'Генерация по образцу (NanoBanana Pro)';

/**
 * Предел числа образцов — три. Причина арифметическая, а не вкусовая.
 *
 * Загруженный файл уходит в тело запроса как `data:`-URL в base64, а тело
 * сервер принимает до 50 МБ (`server/index.ts:312`). base64 добавляет ~37% к
 * размеру, и своего ограничения на размер одной картинки у нас нигде нет:
 * поле принимает любой `image/*`. При четырёх снимках по 9 МБ это уже около
 * 49 МБ ДО промта, стилей и прочих полей — запрос перевалил бы за предел, и
 * человек получил бы отказ сервера без объяснения. Три снимка по 9–10 МБ дают
 * 37–41 МБ и оставляют запас.
 *
 * Поднимать предел можно только вместе с ограничением размера одной картинки
 * (или загрузкой файлов отдельным запросом вместо base64 в теле).
 */
export const MAX_REFERENCE_IMAGES = 3;

/** Поддерживает ли модель вход с образцами. */
export function supportsReference(modelId: string | null | undefined): boolean {
  return modelId === REFERENCE_MODEL_ID;
}

/**
 * Правило из старого кода, которое нельзя потерять при правке: для модели,
 * работающей по образцу, генерация без единого образца запрещена — иначе
 * сервер вернёт 400, а человек увидит непонятную ошибку вместо подсказки.
 * Диалог держит на этом и предупреждение под кнопкой, и саму кнопку.
 */
export function isReferenceMissing(
  modelId: string | null | undefined,
  urls: readonly string[] | null | undefined,
): boolean {
  return supportsReference(modelId) && (urls?.length ?? 0) === 0;
}

/**
 * Часть тела запроса с образцами.
 *
 * Сервер ждёт СПИСОК (`imageUrls`) и умеет несколько
 * (`server/routes-fal-ai-images.ts:298` — проверяет непустой массив и передаёт
 * его целиком), поэтому отдаём все приложенные ссылки, а не первую. Для модели
 * без поддержки не отдаём ничего: лишнее поле в теле только путает лог.
 */
export function referencePayload(
  modelId: string | null | undefined,
  urls: readonly string[] | null | undefined,
): { imageUrls?: string[] } {
  if (!supportsReference(modelId)) return {};
  const clean = (urls || [])
    .map((url) => (typeof url === 'string' ? url.trim() : ''))
    .filter(Boolean)
    .slice(0, MAX_REFERENCE_IMAGES);
  return clean.length > 0 ? { imageUrls: clean } : {};
}
