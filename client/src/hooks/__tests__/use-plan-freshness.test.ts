/**
 * Свежесть профиля при возврате в панель (AI-64).
 *
 * Инцидент 01.08.2026: владелец одобрил тариф в Telegram, вернулся в панель —
 * там прежние значения. Помимо серверной части у этого был и клиентский вклад:
 * профиль кешировался на 5 минут, а `refetchOnWindowFocus` при свежих данных
 * не срабатывает. То есть возврат во вкладку ничего не перечитывал.
 *
 * Тариф меняется ВНЕ приложения (Telegram, письмо), и вкладка узнать об этом
 * может только одним способом — перечитать при возврате. Поэтому здесь
 * закреплено сочетание опций, а не «примерно свежо»: без render-тестов
 * (инфраструктура для них ещё не заведена, AI-59) это единственный способ не
 * дать вернуть 5 минут случайной правкой.
 */

import { describe, it, expect } from 'vitest';
import { PROFILE_FRESHNESS } from '../profile-freshness';

describe('свежесть профиля', () => {
  it('данные не считаются свежими: возврат в панель перечитывает', () => {
    // Любое значение > 0 подавит refetch по фокусу ровно на это время —
    // а тариф мог измениться секунду назад.
    expect(PROFILE_FRESHNESS.staleTime).toBe(0);
  });

  it('возврат во вкладку вызывает перезапрос', () => {
    expect(PROFILE_FRESHNESS.refetchOnWindowFocus).toBe(true);
  });

  it('переход на страницу панели тоже перезапрашивает', () => {
    // Пользователь может вернуться не фокусом окна, а навигацией внутри SPA.
    expect(PROFILE_FRESHNESS.refetchOnMount).toBe(true);
  });
});
