/**
 * AI-49, сторона интерфейса: TikTok не предлагается пользователю.
 *
 * Проверялось руками 17.08.2026: мастер настройки TikTok
 * (`client/src/components/TikTokSetupWizard.tsx`) не импортируется никуда, а
 * список платформ, который рисует интерфейс, состоит из шести штук без TikTok.
 * То есть интерфейс сегодня ничего лишнего не обещает.
 *
 * Тест закрепляет именно это. Пока серверные ручки TikTok недостижимы (см.
 * `server/__tests__/ai49-tiktok-surface.test.ts`), добавление TikTok в список
 * платформ дало бы пользователю кнопки, которые ведут в никуда: запрос ушёл бы
 * на несмонтированный роутер и вернул 404.
 *
 * Решение владельца от 17.08.2026: TikTok в текущем релизе не планируется, но
 * строгого отказа нет. Поэтому платформа остаётся в типах и в серверном коде —
 * убрана только из того, что видит пользователь.
 */
import { describe, it, expect } from 'vitest';
import { safeSocialPlatforms, platformNames } from '../social-platforms';

describe('AI-49: TikTok не показывается в интерфейсе', () => {
  it('TikTok отсутствует в списке предлагаемых платформ', () => {
    expect(safeSocialPlatforms).not.toContain('tiktok');
  });

  it('предлагаются ровно те шесть платформ, которые действительно работают', () => {
    expect([...safeSocialPlatforms].sort()).toEqual(
      ['facebook', 'instagram', 'telegram', 'threads', 'vk', 'youtube'].sort(),
    );
  });

  it('название TikTok в словаре остаётся: платформа известна коду, просто не предлагается', () => {
    // Словарь названий покрывает ВСЕ платформы, включая непредлагаемые:
    // на них ссылаются старые записи публикаций, и подпись для них нужна.
    expect(platformNames.tiktok).toBe('TikTok');
  });
});
