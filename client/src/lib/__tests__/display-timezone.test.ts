/**
 * SM-9: время публикации показывается в московском поясе, а не в поясе браузера.
 *
 * Воспроизведение из тикета: публикация запланирована на 01:00, опубликовалась,
 * но на карточке время отличалось от канала на 3 часа, а на графике активности
 * запись стояла ПРОШЛЫМ числом.
 *
 * Причина одна на оба симптома. Сервер трактует введённое время как московское
 * (server/utils/ru-datetime.ts вычитает +3), поэтому «час ночи» хранится как
 * 22:00Z предыдущих суток. Клиент же форматировал в поясе МАШИНЫ ЗРИТЕЛЯ. Пока
 * все в Москве — совпадает; на машине в UTC получается ровно −3 часа и съехавшая
 * дата.
 *
 * Тесты гоняются с TZ=UTC (см. ниже), то есть в тех же условиях, где баг и
 * ловится. На прежнем коде — formatInTimeZone c resolvedOptions().timeZone и
 * группировка по локальной полуночи — они краснеют.
 */

import { describe, it, expect, vi, afterEach } from 'vitest';
import {
  formatDateWithTimezone,
  formatTimeWithTimezone,
  toDisplayDateKey,
  toWallDateKey,
  displayTodayKey,
  isDisplayToday,
  isSameDisplayDay,
  isInDisplayWeek,
  DISPLAY_TIME_ZONE,
} from '../date-utils';

/** 01:00 МСК 29 июля = 22:00Z 28 июля. Ровно случай из тикета. */
const ONE_AM_MSK = '2026-07-28T22:00:00.000Z';

describe('пояс отображения зафиксирован', () => {
  it('это Москва, а не пояс браузера', () => {
    expect(DISPLAY_TIME_ZONE).toBe('Europe/Moscow');
  });
});

describe('SM-9: публикация в час ночи', () => {
  it('время показывается как 01:00, а не как 22:00', () => {
    expect(formatTimeWithTimezone(ONE_AM_MSK)).toBe('01:00');
  });

  it('дата показывается 29-м числом, а не 28-м', () => {
    expect(formatDateWithTimezone(ONE_AM_MSK, 'dd.MM.yyyy')).toBe('29.07.2026');
  });

  it('ключ дня для группировки — тоже 29-е', () => {
    // Именно из-за него публикация уезжала в предыдущий столбец графика.
    expect(toDisplayDateKey(ONE_AM_MSK)).toBe('2026-07-29');
  });
});

describe('нормализация входных строк', () => {
  it('строка без пояса считается UTC, а не местным временем', () => {
    // Directus отдаёт часть timestamp'ов без Z. Без нормализации браузер
    // трактовал бы такую строку как местное время и добавил ещё один сдвиг.
    expect(toDisplayDateKey('2026-07-28 22:00:00')).toBe('2026-07-29');
  });

  it('строка с явным смещением берётся как есть', () => {
    expect(toDisplayDateKey('2026-07-29T01:00:00+03:00')).toBe('2026-07-29');
  });

  it('объект Date обрабатывается так же, как строка', () => {
    expect(toDisplayDateKey(new Date(ONE_AM_MSK))).toBe('2026-07-29');
  });

  it('пустое и мусорное значение не роняют форматирование', () => {
    expect(toDisplayDateKey(null)).toBeNull();
    expect(toDisplayDateKey('не дата')).toBeNull();
    expect(formatDateWithTimezone(null)).toBe('Дата не указана');
    expect(formatDateWithTimezone('не дата')).toBe('Некорректная дата');
  });
});

describe('граница суток', () => {
  it('23:59 МСК и 00:01 МСК — разные календарные дни', () => {
    // 23:59 МСК 29-го = 20:59Z 29-го; 00:01 МСК 30-го = 21:01Z 29-го.
    // По UTC оба попадают в 29-е, по Москве — в разные сутки.
    expect(toDisplayDateKey('2026-07-29T20:59:00.000Z')).toBe('2026-07-29');
    expect(toDisplayDateKey('2026-07-29T21:01:00.000Z')).toBe('2026-07-30');
  });
});

/**
 * SM-9, вторая половина: ГРУППИРОВКА, а не только форматирование.
 *
 * Находка ревью 2026-07-29. d5e370817 перевёл на Москву вывод времени, но
 * календарь и дашборд продолжали раскладывать записи по локальным суткам:
 * startOfDay / isSameDay / isToday / isThisWeek и new Date(...).getDate().
 *
 * Симптом на браузере в UTC: карточка показывает 01:00 МСК 29 июля, а календарь
 * относит ту же запись к 28-му и дашборд не считает её сегодняшней. Время
 * починили, раскладку — нет.
 */
describe('SM-9: границы суток при группировке', () => {
  const realDateNow = Date.now;

  afterEach(() => {
    vi.useRealTimers();
    Date.now = realDateNow;
  });

  /** Замораживает «сейчас» на указанном моменте. */
  const freezeAt = (iso: string) => {
    vi.useFakeTimers();
    vi.setSystemTime(new Date(iso));
  };

  it('01:00 МСК 29-го попадает в московские сутки 29-го, а не 28-го', () => {
    // На машине в UTC локальные сутки этого момента — 28 июля.
    expect(new Date(ONE_AM_MSK).getUTCDate()).toBe(28);
    expect(toDisplayDateKey(ONE_AM_MSK)).toBe('2026-07-29');
  });

  it('московское «сегодня» включает публикацию, сделанную в час ночи', () => {
    // «Сейчас» — 10:00 МСК 29 июля.
    freezeAt('2026-07-29T07:00:00.000Z');

    expect(displayTodayKey()).toBe('2026-07-29');
    expect(isDisplayToday(ONE_AM_MSK)).toBe(true);
  });

  it('граница 23:59 МСК принадлежит уходящим суткам', () => {
    // 23:59 МСК 29 июля = 20:59Z 29 июля.
    expect(toDisplayDateKey('2026-07-29T20:59:00.000Z')).toBe('2026-07-29');
  });

  it('граница 00:01 МСК принадлежит уже наступившим суткам', () => {
    // 00:01 МСК 30 июля = 21:01Z 29 июля.
    expect(toDisplayDateKey('2026-07-29T21:01:00.000Z')).toBe('2026-07-30');
  });

  it('выбранный в календаре день — стенная дата, поясом её не двигаем', () => {
    // Виджет отдаёт локальную полночь 29 июля. У зрителя в UTC пересчёт в
    // Москву дал бы 29-е + 3 часа — то есть тоже 29-е; а вот у зрителя западнее
    // Москвы (см. следующий тест) выбор уехал бы на сутки назад.
    const picked = new Date(2026, 6, 29, 0, 0, 0);
    expect(toWallDateKey(picked)).toBe('2026-07-29');
  });

  it('публикация из ночи 29-го видна в календарной клетке 29-го', () => {
    const picked = new Date(2026, 6, 29, 0, 0, 0);

    // Именно так календарь и обязан сравнивать: стенная дата клетки против
    // московского дня публикации.
    expect(toWallDateKey(picked)).toBe(toDisplayDateKey(ONE_AM_MSK));
  });

  it('одни и те же московские сутки распознаются у моментов с разных календарных дат UTC', () => {
    // 23:00 МСК 29-го (20:00Z 29-го) и 01:00 МСК 29-го (22:00Z 28-го).
    expect(isSameDisplayDay('2026-07-29T20:00:00.000Z', ONE_AM_MSK)).toBe(true);
  });

  it('неделя считается с понедельника и по московской границе', () => {
    // 29 июля 2026 — среда. Замораживаем на 10:00 МСК среды.
    freezeAt('2026-07-29T07:00:00.000Z');

    // Понедельник той же недели, 01:00 МСК 27-го = 22:00Z 26-го.
    expect(isInDisplayWeek('2026-07-26T22:00:00.000Z')).toBe(true);
    // Воскресенье ПРЕДЫДУЩЕЙ недели, 23:00 МСК 26-го = 20:00Z 26-го.
    // При старте недели с воскресенья этот момент ошибочно попал бы в текущую.
    expect(isInDisplayWeek('2026-07-26T20:00:00.000Z')).toBe(false);
  });

  it('ночная публикация 29-го входит в текущую неделю', () => {
    freezeAt('2026-07-29T07:00:00.000Z');
    expect(isInDisplayWeek(ONE_AM_MSK)).toBe(true);
  });
});

/**
 * Зритель ВОСТОЧНЕЕ Москвы: там локальные сутки, наоборот, опережают московские.
 *
 * Прежний локальный код ошибался в обе стороны, поэтому проверяем и эту.
 */
describe('SM-9: зритель восточнее Москвы', () => {
  it('вечерняя московская публикация не уезжает у него на завтра', () => {
    // 23:00 МСК 29 июля = 20:00Z 29-го. Во Владивостоке (UTC+10) это уже
    // 06:00 30 июля — локальная группировка отнесла бы запись к 30-му.
    const lateEveningMsk = '2026-07-29T20:00:00.000Z';

    expect(toDisplayDateKey(lateEveningMsk)).toBe('2026-07-29');
    // Проверка независима от пояса машины: ключ считается по Москве всегда.
    expect(new Date(lateEveningMsk).getTime()).toBe(Date.parse(lateEveningMsk));
  });
});
