/**
 * SM-9: время публикации показывается в московском поясе, а не в поясе браузера.
 *
 * Воспроизведение из тикета: публикация запланирована на 01:00, опубликовалась,
 * но на карточке время отличалось от канала на 3 часа, а на графике активности
 * запись стояла ПРОШЛЫМ числом.
 *
 * Причина одна на оба симптома. Сервер трактует введённое время как московское
 * (server/utils/ru-datetime.ts вычитает +3), поэтому «час ночи» хранится как
 * 22:00Z предыдущих суток. Клиент же форматировал в поясе МАШИНЫ ЗРИТЕЛЯ. Пока
 * все в Москве — совпадает; на машине в UTC получается ровно −3 часа и съехавшая
 * дата.
 *
 * Тесты гоняются с TZ=UTC (см. ниже), то есть в тех же условиях, где баг и
 * ловится. На прежнем коде — formatInTimeZone c resolvedOptions().timeZone и
 * группировка по локальной полуночи — они краснеют.
 */

import { describe, it, expect } from 'vitest';
import {
  formatDateWithTimezone,
  formatTimeWithTimezone,
  toDisplayDateKey,
  DISPLAY_TIME_ZONE,
} from '../date-utils';

/** 01:00 МСК 29 июля = 22:00Z 28 июля. Ровно случай из тикета. */
const ONE_AM_MSK = '2026-07-28T22:00:00.000Z';

describe('пояс отображения зафиксирован', () => {
  it('это Москва, а не пояс браузера', () => {
    expect(DISPLAY_TIME_ZONE).toBe('Europe/Moscow');
  });
});

describe('SM-9: публикация в час ночи', () => {
  it('время показывается как 01:00, а не как 22:00', () => {
    expect(formatTimeWithTimezone(ONE_AM_MSK)).toBe('01:00');
  });

  it('дата показывается 29-м числом, а не 28-м', () => {
    expect(formatDateWithTimezone(ONE_AM_MSK, 'dd.MM.yyyy')).toBe('29.07.2026');
  });

  it('ключ дня для группировки — тоже 29-е', () => {
    // Именно из-за него публикация уезжала в предыдущий столбец графика.
    expect(toDisplayDateKey(ONE_AM_MSK)).toBe('2026-07-29');
  });
});

describe('нормализация входных строк', () => {
  it('строка без пояса считается UTC, а не местным временем', () => {
    // Directus отдаёт часть timestamp'ов без Z. Без нормализации браузер
    // трактовал бы такую строку как местное время и добавил ещё один сдвиг.
    expect(toDisplayDateKey('2026-07-28 22:00:00')).toBe('2026-07-29');
  });

  it('строка с явным смещением берётся как есть', () => {
    expect(toDisplayDateKey('2026-07-29T01:00:00+03:00')).toBe('2026-07-29');
  });

  it('объект Date обрабатывается так же, как строка', () => {
    expect(toDisplayDateKey(new Date(ONE_AM_MSK))).toBe('2026-07-29');
  });

  it('пустое и мусорное значение не роняют форматирование', () => {
    expect(toDisplayDateKey(null)).toBeNull();
    expect(toDisplayDateKey('не дата')).toBeNull();
    expect(formatDateWithTimezone(null)).toBe('Дата не указана');
    expect(formatDateWithTimezone('не дата')).toBe('Некорректная дата');
  });
});

describe('граница суток', () => {
  it('23:59 МСК и 00:01 МСК — разные календарные дни', () => {
    // 23:59 МСК 29-го = 20:59Z 29-го; 00:01 МСК 30-го = 21:01Z 29-го.
    // По UTC оба попадают в 29-е, по Москве — в разные сутки.
    expect(toDisplayDateKey('2026-07-29T20:59:00.000Z')).toBe('2026-07-29');
    expect(toDisplayDateKey('2026-07-29T21:01:00.000Z')).toBe('2026-07-30');
  });
});
