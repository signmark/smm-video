/**
 * Заглушка «Адаптировать под площадки» (решение владельца 19.08).
 *
 * Кнопка адаптации не сохраняла ничего никогда: сервер только отправлял задание
 * в n8n, а n8n из продукта выведен. AI-128 убрала ложный успех, но человек всё
 * равно узнавал о неудаче ПОСЛЕ того, как написал текст под три площадки.
 * Владелец решил реализацию отложить (SM-35) и до тех пор показывать честную
 * заглушку — до начала работы, а не после.
 *
 * Модуль временный: уходит вместе с SM-35, поэтому вся заглушка собрана здесь,
 * а не размазана по диалогу.
 */

/** Пока сохранение не сделано — правда одна на весь интерфейс. */
export const ADAPT_SAVING_AVAILABLE = false;

export const ADAPT_COMING_SOON_NOTICE =
  'Сохранение текстов по площадкам скоро появится. Сейчас их можно посмотреть и подготовить, но сохранить пока нельзя.';

export interface AdaptSaveState {
  disabled: boolean;
  label: string;
}

/**
 * Состояние кнопки сохранения. Пока функция не реализована, кнопка выключена
 * при любом наборе выбранных площадок: включённая кнопка обещает работу,
 * которой не будет.
 */
export function adaptSaveState(input: {
  saving: boolean;
  anyPlatformEnabled: boolean;
}): AdaptSaveState {
  if (!ADAPT_SAVING_AVAILABLE) {
    return { disabled: true, label: 'Скоро появится' };
  }
  if (input.saving) {
    return { disabled: true, label: 'Сохранение...' };
  }
  return { disabled: !input.anyPlatformEnabled, label: 'Сохранить' };
}
