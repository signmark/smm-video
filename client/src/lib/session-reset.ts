import { subscribeToSessionEvents } from './sessionCoordinator';
import { useStoryStore } from './storyStore';
import { useSimpleStoryStore } from './simpleStoryStore';

/**
 * Сброс пользовательских данных при выходе из аккаунта (AI-79).
 *
 * Зачем. `clearAuth` чистит токен, ключи localStorage и выбранную кампанию, но
 * черновики сторис живут в отдельных сторах и переживали выход. Раньше это
 * маскировала полная перезагрузка страницы, и то лишь на публичных маршрутах;
 * после перевода логаута на SPA-навигацию (AI-77) маскировка исчезла совсем.
 * На общем браузере — обычная ситуация в агентстве — следующий вошедший видел
 * чужой черновик до ручного обновления страницы.
 *
 * Почему подписка, а не перечисление сторов внутри `clearAuth`: список,
 * который ведут руками, расходится с реальностью на следующем добавленном
 * сторе. Здесь стор сам отвечает за свою очистку, а точка входа одна.
 *
 * Почему регистрация явная, а не при импорте: подписка на уровне модуля — это
 * побочный эффект импорта. Такой код уже дважды ломал нам посторонние тесты
 * (AI-45 с zustand-сторами, AI-55 с сетевой пробой), поэтому вызывается
 * осознанно из точки старта приложения.
 *
 * Реагируем ТОЛЬКО на `account-changed`, то есть на явный выход. Событие
 * `invalid` приходит и при неудачной попытке обновить токен, когда человек
 * продолжает работать, — сбросить по нему черновик значило бы уничтожить
 * несохранённую работу живого пользователя.
 */
export function registerSessionReset(): () => void {
  return subscribeToSessionEvents((status) => {
    if (status !== 'account-changed') return;

    useStoryStore.getState().resetStore();
    useSimpleStoryStore.getState().clearStore();
  });
}
