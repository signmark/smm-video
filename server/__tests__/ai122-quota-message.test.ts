/**
 * AI-122: сообщение об исчерпании лимита должно называть доступное действие.
 *
 * ПОВОД. Тестировщик на пробном тарифе упёрся в лимит генерации изображений и
 * пошёл к владельцу продукта. Сообщение при этом было не сырое и не про ошибку:
 * «Лимит генераций исчерпан (10/10 в месяц). Оформите подписку для продолжения».
 * Но действия оно не называло. А действие есть — в разделе «Тарифы» отправляется
 * заявка на повышение, которую администратор одобряет вручную. Человек об этом
 * не знал и пошёл спрашивать живого человека.
 *
 * Поэтому проверяется не «текст не пустой», а три вещи по существу: что именно
 * исчерпано, когда обновится, что делать сейчас.
 */
import { describe, it, expect } from 'vitest';
import {
  quotaResetsAt,
  formatResetDate,
  quotaInfo,
  quotaExceededMessage,
  QUOTA_UPGRADE_PATH,
} from '../services/image-gen-quota';

describe('AI-122: когда обнулится счётчик', () => {
  it('обновление — первое число следующего месяца', () => {
    // Расход считается по календарному месяцу (image-gen-tracker), поэтому
    // «через 30 дней» было бы неправдой: человек, исчерпавший лимит 31 августа,
    // получит новый на следующий день.
    expect(quotaResetsAt(new Date('2026-08-17T12:00:00Z')).toISOString())
      .toBe('2026-09-01T00:00:00.000Z');
    expect(quotaResetsAt(new Date('2026-08-31T23:59:59Z')).toISOString())
      .toBe('2026-09-01T00:00:00.000Z');
  });

  it('декабрь переходит в январь следующего года', () => {
    expect(quotaResetsAt(new Date('2026-12-05T00:00:00Z')).toISOString())
      .toBe('2027-01-01T00:00:00.000Z');
  });

  it('дата называется по-человечески, а не машинным временем', () => {
    expect(formatResetDate(new Date('2026-09-01T00:00:00Z'))).toBe('1 сентября');
    expect(formatResetDate(new Date('2027-01-01T00:00:00Z'))).toBe('1 января');
  });
});

describe('AI-122: текст сообщения', () => {
  const NOW = new Date('2026-08-17T12:00:00Z');

  it('называет, что именно исчерпано, и в каком объёме', () => {
    const msg = quotaExceededMessage(10, 10, NOW);
    expect(msg).toContain('10 из 10');
    expect(msg.toLowerCase()).toContain('изображени');
  });

  it('называет, когда лимит обновится', () => {
    expect(quotaExceededMessage(10, 10, NOW)).toContain('1 сентября');
  });

  it('называет доступное действие, а не призыв платить', () => {
    const msg = quotaExceededMessage(30, 30, NOW);
    // Действие, которое человек может выполнить сам, не спрашивая никого.
    expect(msg).toContain('Тарифы');
    expect(msg.toLowerCase()).toContain('запросите повышение');

    // «Оформите подписку» звучит как «идите куда-то платить», хотя платить
    // прямо сейчас не требуется: достаточно заявки. Именно из-за этой фразы
    // человек и пошёл искать живого человека.
    expect(msg).not.toContain('Оформите подписку');
    expect(msg).not.toContain('Pro');
  });

  it('текст один и тот же независимо от тарифа — расходиться нечему', () => {
    // Раньше он был написан дважды в разных маршрутах и уже начал расходиться.
    const trial = quotaExceededMessage(10, 10, NOW);
    const basic = quotaExceededMessage(30, 30, NOW);
    expect(trial.replace('10 из 10', 'N')).toBe(basic.replace('30 из 30', 'N'));
  });
});

describe('AI-122: машинная часть ответа', () => {
  const NOW = new Date('2026-08-17T12:00:00Z');

  it('несёт остаток, дату обновления и путь к заявке', () => {
    const info = quotaInfo(10, 10, NOW);
    expect(info).toMatchObject({
      count: 10,
      limit: 10,
      remaining: 0,
      resetsAt: '2026-09-01T00:00:00.000Z',
      upgradePath: QUOTA_UPGRADE_PATH,
    });
  });

  it('остаток не уходит в минус при перерасходе', () => {
    // Счётчик может обогнать лимит: параллельные генерации инкрементируют его
    // независимо. Отрицательный остаток в интерфейсе выглядел бы поломкой.
    expect(quotaInfo(12, 10, NOW).remaining).toBe(0);
  });

  it('путь к заявке ведёт на существующую страницу тарифов', () => {
    expect(QUOTA_UPGRADE_PATH).toBe('/pricing');
  });
});
