/**
 * AI-41: разделение «жив» и «готов».
 *
 * Зачем два разных ответа. Вопрос «жив ли процесс» и вопрос «может ли он
 * обслуживать запросы» — разные, и путать их дорого. Выкатка спрашивает первое:
 * ей нужно понять, поднялся ли новый код, и ответ не должен зависеть от чужих
 * сервисов. Мониторинг и дежурный спрашивают второе: если лёг Directus,
 * приложение живо, но бесполезно, и это надо видеть сразу, а не выяснять
 * раскопками.
 *
 * Что было до этой правки. Проверка зависимостей существовала, но висела на
 * `/api/health` — за общей проверкой доступа, поэтому снаружи отвечала 401 и
 * мониторингу была недоступна. Общепринятые имена `/live` и `/ready` не были
 * заняты вовсе и попадали в отдачу одностраничного приложения: любой монитор,
 * настроенный на них, получал 200 и страницу вместо приговора. Это хуже
 * отсутствия проверки — молчаливое «всё хорошо» при лежащем сервисе.
 *
 * Почему решение вынесено отдельной функцией, а не написано внутри обработчика:
 * приговор «готов / не готов» надо покрыть тестами, не поднимая ни сервер, ни сеть.
 */

/** Стабильный код причины. Намеренно НЕ текст ошибки: в него попадают адреса,
 *  имена бакетов и параметры подключения, а ответ ручки виден снаружи. */
export type DependencyReason = 'unreachable' | 'timeout' | 'rejected';

export interface DependencyProbe {
  name: string;
  /** Обязательная зависимость: её отказ делает приложение не готовым.
   *  Необязательная попадает в ответ, но приговор не меняет. */
  required: boolean;
  status: 'up' | 'down';
  reason?: DependencyReason;
  duration_ms: number;
}

export interface ReadinessVerdict {
  ready: boolean;
  httpStatus: 200 | 503;
  dependencies: DependencyProbe[];
}

/**
 * Приговор о готовности. Не готов — если легла хотя бы одна ОБЯЗАТЕЛЬНАЯ
 * зависимость. Необязательные видны в ответе, но приговор не меняют: иначе
 * мигание второстепенного сервиса будет выглядеть как отказ приложения.
 */
export function decideReadiness(probes: DependencyProbe[]): ReadinessVerdict {
  const ready = !probes.some((p) => p.required && p.status === 'down');
  return { ready, httpStatus: ready ? 200 : 503, dependencies: probes };
}

/**
 * Разбор попытки достучаться до объектного хранилища.
 *
 * Тонкость, на которой уже ошиблись в `/api/health`: наш бакет на анонимный
 * HEAD отвечает 403. Это не поломка, а ровно наоборот — DNS разрешился, TLS
 * поднялся, сервер ответил. Прежний код ловил исключение axios и записывал
 * хранилище в «недоступно», то есть исправное хранилище постоянно числилось
 * сломанным. Поэтому признак живости здесь — «пришёл ЛЮБОЙ код HTTP»,
 * а отказ — только когда ответа не было вовсе.
 */
export function classifyStorageOutcome(outcome: {
  httpStatus?: number;
  errorCode?: string;
}): { status: 'up' | 'down'; reason?: DependencyReason } {
  if (typeof outcome.httpStatus === 'number') {
    return { status: 'up' };
  }
  if (outcome.errorCode === 'ECONNABORTED' || outcome.errorCode === 'ETIMEDOUT') {
    return { status: 'down', reason: 'timeout' };
  }
  return { status: 'down', reason: 'unreachable' };
}
