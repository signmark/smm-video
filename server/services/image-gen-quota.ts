/**
 * AI-122: что сказать человеку, когда месячный лимит генераций исчерпан.
 *
 * ПОВОД. Тестировщик на пробном тарифе упёрся в лимит и пошёл к владельцу
 * продукта. Сообщение при этом было: «Лимит генераций исчерпан (10/10 в месяц).
 * Оформите подписку для продолжения». Оно не сырое и не про ошибку — но оно не
 * называет ни одного действия, доступного человеку прямо сейчас.
 *
 * А действие есть: в разделе «Тарифы» отправляется заявка на повышение, и
 * администратор одобряет её вручную. Человек об этом не знал, поэтому пошёл
 * искать живого человека — что с его стороны совершенно разумно.
 *
 * Поэтому текст сообщения собирается здесь, в одном месте, и содержит три вещи:
 * что именно исчерпано, когда обновится, что можно сделать сейчас. Два вызова
 * в разных маршрутах раньше писали это порознь и уже начали расходиться.
 */

/** Куда ведём человека за повышением тарифа. Заявку одобряет администратор. */
export const QUOTA_UPGRADE_PATH = '/pricing';

const MONTHS_GENITIVE = [
  'января', 'февраля', 'марта', 'апреля', 'мая', 'июня',
  'июля', 'августа', 'сентября', 'октября', 'ноября', 'декабря',
];

/**
 * Когда счётчик обнулится. Расход считается по календарному месяцу
 * (см. image-gen-tracker), поэтому обновление — первое число следующего.
 */
export function quotaResetsAt(now: Date): Date {
  return new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth() + 1, 1));
}

/** «1 сентября» — так, как это скажет человек, а не 2026-09-01T00:00:00Z. */
export function formatResetDate(at: Date): string {
  return `${at.getUTCDate()} ${MONTHS_GENITIVE[at.getUTCMonth()]}`;
}

export interface QuotaInfo {
  count: number;
  limit: number;
  remaining: number;
  resetsAt: string;
  upgradePath: string;
}

export function quotaInfo(count: number, limit: number, now: Date): QuotaInfo {
  const resets = quotaResetsAt(now);
  return {
    count,
    limit,
    remaining: Math.max(0, limit - count),
    resetsAt: resets.toISOString(),
    upgradePath: QUOTA_UPGRADE_PATH,
  };
}

/**
 * Текст для человека. Намеренно без слов «тариф Pro» и «оформите подписку»:
 * первое ничего не говорит о том, что делать, второе звучит как «идите куда-то
 * платить», хотя платить прямо сейчас не требуется — достаточно заявки.
 */
export function quotaExceededMessage(count: number, limit: number, now: Date): string {
  return (
    `Лимит генераций изображений исчерпан: ${count} из ${limit} в этом месяце. ` +
    `Счётчик обнулится ${formatResetDate(quotaResetsAt(now))}. ` +
    `Если нужно больше сейчас — запросите повышение тарифа в разделе «Тарифы», ` +
    `заявку рассматривает администратор.`
  );
}
