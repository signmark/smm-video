/**
 * Экранирование подстановок в HTML писем.
 *
 * Имя, почта и прочие пользовательские поля попадают в разметку письма через
 * шаблонные строки. Без экранирования любой символ разметки в имени
 * пользователя ломает вёрстку письма, а в худшем случае вставляет в него
 * чужой тег или ссылку. Стреляет слабо (письмо обычно уходит на собственный
 * адрес), но неэкранированная интерполяция в разметку — это дефект сам по
 * себе, и чинится он в одном месте.
 *
 * Экранируем и кавычки: подстановка может оказаться внутри значения
 * атрибута, а не только в тексте узла.
 */
export function escapeHtml(value: unknown): string {
  if (value === null || value === undefined) return '';
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
